export function getActiveAlerts() {
  return mockAlerts.filter(a => a.status !== 'resolved');
}

export function getAlertsByMine(mineId) {
  return mockAlerts.filter(a => a.mineId === mineId);
}

export function getAlertStats() {
  const active = mockAlerts.filter(a => a.status === 'active').length;
  const critical = mockAlerts.filter(a => a.severity === 'critical' && a.status !== 'resolved').length;
  const high = mockAlerts.filter(a => a.severity === 'high' && a.status !== 'resolved').length;
  return { active, critical, high, total: mockAlerts.length };
}
