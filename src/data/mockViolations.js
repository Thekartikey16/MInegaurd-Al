export function getViolationsByMine(mineId) {
  return mockViolations.filter(v => v.mineId === mineId);
}

export function getOpenViolations() {
  return mockViolations.filter(v => !['resolved', 'closed'].includes(v.status));
}

export function getViolationStats() {
  const total = mockViolations.length;
  const open = mockViolations.filter(v => v.status === 'open').length;
  const critical = mockViolations.filter(v => v.severity === 'critical').length;
  const resolved = mockViolations.filter(v => v.status === 'resolved').length;
  const aiDetected = mockViolations.filter(v => v.aiDetected).length;
  return { total, open, critical, resolved, aiDetected };
}
